import test from 'node:test';
import assert from 'node:assert/strict';
import * as R from './rules.js';
import {recordContract,contractsStatus,restoreContracts,localDay} from './campaign-contracts.js';
const t=Date.UTC(2026,9,31,12);
test('contracts are optional, cannot be claimed early, and grant bounded rewards only once',()=>{
  const s=R.createState(t),before={...s.res};
  assert.equal(R.claimCampaignContract(s,'supply',t).ok,false);
  assert.equal(R.collect(s,t+60000).ok,true);
  assert.equal(contractsStatus(s,t).contracts[0].progress,1);
  assert.equal(R.claimCampaignContract(s,'supply',t).ok,true);
  assert.equal(s.res.gold,before.gold+20+60);
  assert.equal(s.res.wood,before.wood+15+35);
  const saved=JSON.stringify(s);
  assert.equal(R.claimCampaignContract(s,'supply',t).ok,false);
  assert.deepEqual(s,JSON.parse(saved));
  assert.equal(s.contracts.totalClaims,1);
});
test('new day resets tasks but never erases earned cosmetic banner milestones',()=>{
  const s=R.createState(t);
  for(const kind of ['collect','win','ability','ability'])recordContract(s,kind,t);
  for(const c of ['supply','victory','tactics'])assert.equal(R.claimCampaignContract(s,c,t).ok,true);
  assert.equal(contractsStatus(s,t).earned[0],'Yeminli İzci');
  assert.equal(R.claimCampaignContract(s,'supply',t).ok,false);
  const next=t+86400000;
  assert.equal(contractsStatus(s,next).contracts[0].progress,0);
  assert.equal(R.claimCampaignContract(s,'supply',next).ok,false);
  recordContract(s,'collect',next);
  assert.equal(R.claimCampaignContract(s,'supply',next).ok,true);
  assert.equal(s.contracts.totalClaims,4);
  assert.deepEqual(contractsStatus(s,next).earned,['Yeminli İzci']);
});
test('old saves, malformed values and clock rollback do not create free claims',()=>{
  const s=R.restoreState({version:1},t);
  assert.equal(s.contracts.totalClaims,0);
  const corrupt={day:localDay(t),progress:{supply:1e9,victory:-7,tactics:'2'},claimed:{supply:'true'},totalClaims:Infinity};
  const repaired=restoreContracts(corrupt,t);
  assert.deepEqual(repaired.progress,{supply:1,victory:0,tactics:0});
  assert.equal(repaired.totalClaims,0);
  recordContract(s,'collect',t);R.claimCampaignContract(s,'supply',t);
  assert.equal(R.claimCampaignContract(s,'supply',t-86400000).ok,false);
});
test('veteran stage requires first clear and increasing enemy pressure, award is idempotent',()=>{
  const s=R.createState(t);
  assert.equal(R.startVeteranBattle(s,1,1).ok,false);
  s.cleared=[1];
  const normal=R.startBattle(s,1);
  assert.equal(normal.ok,true);
  const enemyHp=s.battle.enemies[0].maxHp;
  s.battle=null;
  assert.equal(R.startVeteranBattle(s,1,2).ok,true);
  assert.equal(s.battle.veteranTier,2);
  assert.ok(s.battle.enemies[0].maxHp>enemyHp);
  assert.ok(s.battle.enemies[0].attack>10);
  const restored=R.restoreState(JSON.stringify(s),t);
  assert.equal(restored.battle?.veteranTier,2);
  assert.equal(restored.battle.enemies[0].maxHp,s.battle.enemies[0].maxHp);
  const res={...s.res};
  for(const enemy of s.battle.enemies)enemy.hp=0;
  // battleTurn sees no enemies left, so settles and awards the already-cleared map once.
  s.battle.live=null;
  const completed=R.battleTurn(s,'strike');
  assert.equal(completed.ok,true);
  assert.equal(s.veteranMedals[1],2);
  const after={...s.res};
  assert.equal(R.battleTurn(s,'strike').ok,false);
  assert.deepEqual(s.res,after);
  assert.ok(after.gold>res.gold);
});
