import test from 'node:test';
import assert from 'node:assert/strict';
import * as R from './rules.js';
import {buildingUpgradePlan,buildingRoadmap} from './building-planner.js';
import {buildingWorkshopMarkup} from './building-workshop.js';
const NOW=Date.UTC(2026,10,2,12);
const copy=x=>JSON.parse(JSON.stringify(x));
const fresh=()=>R.createState(NOW);
const art={icon:()=>'<svg></svg>',number:n=>String(n),now:NOW};
const unchanged=(s,action)=>{const before=copy(s);const result=action();assert.equal(result.ok,false);assert.deepEqual(s,before);};
test('whole economy has twenty levels, slower output, deliberately long single-builder schedule',()=>{
 const state=fresh();
 assert.equal(R.BUILDINGS.length,7);
 assert.ok(R.BUILDINGS.every(b=>b.maxLevel===20));
 assert.deepEqual(R.production(state,NOW+60000),{gold:4,wood:3,stone:2,aether:0});
 assert.equal(R.constructionDuration(1),0);
 assert.equal(R.constructionDuration(2),3*60000);
 assert.equal(R.constructionDuration(8),300*60000);
 assert.equal(R.constructionDuration(19),3600*60000);
 const serial=R.BUILDINGS.length*Array.from({length:18},(_,i)=>R.constructionDuration(i+2)).reduce((a,b)=>a+b,0);
 assert.ok(serial>=75*24*3600000,'single builder cannot finish seven buildings in under 75 days');
});
test('level two remains quick tutorial, level three is timed and waits even with resources',()=>{
 const s=fresh();
 assert.equal(R.upgradeBuilding(s,'keep',NOW).ok,true);
 assert.equal(s.buildings.keep,2);
 s.res={gold:100000,wood:100000,stone:100000,aether:10000};
 const cost=R.upgradeCost(s,'keep'),before=copy(s.res);
 const action=R.upgradeBuilding(s,'keep',NOW);
 assert.equal(action.ok,true);assert.equal(action.started,true);
 assert.equal(action.durationMs,3*60000);assert.equal(s.buildings.keep,2);
 for(const [resource,amount] of Object.entries(cost))assert.equal(s.res[resource],before[resource]-amount);
 unchanged(s,()=>R.upgradeBuilding(s,'farm',NOW+10000));
 unchanged(s,()=>R.completeConstruction(s,NOW+action.durationMs-1));
 assert.equal(R.completeConstruction(s,NOW+action.durationMs).ok,true);
 assert.equal(s.buildings.keep,3);assert.equal(s.construction,null);
 unchanged(s,()=>R.completeConstruction(s,NOW+action.durationMs));
});
test('saved construction resumes after reloading and cannot be accelerated by invalid records',()=>{
 const s=fresh();s.res={gold:300000,wood:300000,stone:300000,aether:300000};
 R.upgradeBuilding(s,'keep',NOW);R.upgradeBuilding(s,'keep',NOW);
 const raw=copy(s), restored=R.restoreState(raw,NOW+2*60000);
 assert.deepEqual(restored.construction,s.construction);
 assert.equal(R.constructionStatus(restored,NOW+2*60000).remainingMs,60000);
 assert.equal(R.constructionStatus(restored,NOW+3*60000).ready,true);
 assert.equal(R.completeConstruction(restored,NOW+3*60000).ok,true);
 assert.equal(restored.buildings.keep,3);
 const broken=copy(s);broken.construction.endsAt-=60000;
 assert.equal(R.restoreState(broken,NOW+4*60000).construction,null);
 broken.construction.id='__proto__';
 assert.equal(R.restoreState(broken,NOW+4*60000).construction,null);
});
test('long game star gates reward replayable battle results rather than spending only',()=>{
 const s=fresh();s.res={gold:500000,wood:500000,stone:500000,aether:500000};
 s.buildings.keep=4;
 const first=R.buildingMasteryGate(s,'keep');
 assert.equal(first.required,3);assert.equal(first.ok,false);
 unchanged(s,()=>R.upgradeBuilding(s,'keep',NOW));
 s.cleared=[1];
 s.campaignStars={1:3};
 assert.equal(R.buildingMasteryGate(s,'keep').ok,true);
 const action=R.upgradeBuilding(s,'keep',NOW);
 assert.equal(action.started,true);
 assert.equal(s.buildings.keep,4);
 s.construction=null;
 s.buildings.keep=18;
 assert.equal(R.buildingMasteryGate(s,'keep').required,24);
 unchanged(s,()=>R.upgradeBuilding(s,'keep',NOW));
 s.cleared=Array.from({length:8},(_,i)=>i+1);
 s.campaignStars=Object.fromEntries(s.cleared.map(i=>[i,3]));
 assert.equal(R.buildingMasteryGate(s,'keep').ok,true);
});
test('endgame production and costs are finite; all buildings cannot be instantly bought',()=>{
 const s=fresh();s.res={gold:1e9,wood:1e9,stone:1e9,aether:1e9};
 s.buildings.keep=20;
 const upgrades=R.BUILDINGS.filter(b=>b.id!=='keep');
 for(const b of upgrades){
   s.buildings[b.id]=19;
   const plan=buildingUpgradePlan(s,b.id,NOW);
   assert.equal(plan.level,19);
   assert.equal(plan.nextLevel,20);
   assert.ok(plan.cost.gold>10000);
   assert.ok(plan.durationMs>=2*24*3600000);
 }
 const report=buildingRoadmap(s,NOW);
 assert.equal(report.plans.length,7);
 const html=buildingWorkshopMarkup(s,'farm',art);
 assert.match(html,/Köy gelişimi/);
 assert.match(html,/data-workshop-expedition/);
 assert.match(html,/20/);
 assert.doesNotMatch(html,/data-building-preview="20"/,'only the eight real facade variants may be painted');
});
test('pending production spends atomically at tier 3; no double payment or instant win',()=>{
 const s=fresh();
 s.buildings.keep=2;
 s.res={gold:1,wood:1,stone:1,aether:1};
 const future=NOW+3*3600000;
 const plan=buildingUpgradePlan(s,'farm',future);
 assert.equal(plan.status,'collect');
 const action=R.upgradeBuildingFromProduction(s,'farm',future);
 assert.equal(action.ok,true);assert.equal(action.started??false,false);assert.equal(s.buildings.farm,2);
 const at=R.upgradeBuildingFromProduction(s,'farm',future);
 assert.equal(at.ok,true);assert.equal(at.started,true);
 assert.equal(s.buildings.farm,2);
 unchanged(s,()=>R.upgradeBuildingFromProduction(s,'quarry',future));
});
