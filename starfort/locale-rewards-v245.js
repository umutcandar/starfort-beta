export function rewardText(key,variables={}){
 const locale=getLocale();
 const message=REWARD_TRANSLATIONS[locale]?.[key]??REWARD_TRANSLATIONS.en[key];
 if(message===undefined)return key;
 return message.replace(/\{(\w+)\}/g,(_,name)=>String(variables[name]??''));
}
