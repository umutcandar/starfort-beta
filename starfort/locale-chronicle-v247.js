export function auditChronicleTranslations(){return SUPPORTED_LOCALES.flatMap(locale=>{
 const p=CHRONICLE_TRANSLATIONS[locale];if(!p)return [locale+':missing'];
 return [...(p.sigils.length===10?[]:[locale+':sigils']),...(p.ranks.length===3?[]:[locale+':ranks']),...CHRONICLE_UI_KEYS.filter(k=>!p.ui[k]?.trim()).map(k=>locale+':'+k)];
});}
