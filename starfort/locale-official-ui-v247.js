export const OFFICIAL_TRANSLATIONS=Object.freeze(Object.fromEntries(Object.entries(TRANSLATED).map(([lang,words])=>[lang,Object.freeze(Object.fromEntries(OFFICIAL_KEYS.map((k,i)=>[k,words[i]])))])));
/** English phrase is the stable lookup ID for existing local(tr,en) calls. */
export function officialText(tr,en){
 const lang=getLocale();
 if(lang==='tr')return tr;
 if(lang==='en')return en;
 return OFFICIAL_TRANSLATIONS[lang]?.[en]??en;
}
export function auditOfficialTranslations(){
 return SUPPORTED_LOCALES.filter(lang=>lang!=='tr'&&lang!=='en').flatMap(lang=>OFFICIAL_KEYS.filter(k=>!OFFICIAL_TRANSLATIONS[lang]?.[k]?.trim()).map(k=>lang+':'+k));
}
